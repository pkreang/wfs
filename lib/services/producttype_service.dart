import 'dart:convert';
import 'package:http/http.dart' as http;
import 'package:wfs/config/api_config.dart';
import 'package:wfs/models/producttype_model.dart';

class ProductTypeService {
  Future<ProductType> Add(String accessToken, ProductType productType) async {
    if (accessToken.isEmpty) {
      throw Exception('Authentication token is not available.');
    }
    try {
      final response = await http.post(
        Uri.parse(ApiConfig.addProductTypeUrl),
        headers: {
          'Content-Type': 'application/json',
          'Accept': 'application/json',
          'Authorization': 'Bearer $accessToken',
        },
        body: json.encode(productType),
      );
      if (response.statusCode == 200) {
        final data = json.decode(response.body);
        final dynamic ProductListJson = data['product_type'];
        return ProductType.fromJson(ProductListJson);
      } else {
        throw Exception(
          'Failed to load Clients. Status code: ${response.statusCode}',
        );
      }
    } catch (e) {
      throw Exception('Failed to load Clients. Status code: ');
    }
  }
}
